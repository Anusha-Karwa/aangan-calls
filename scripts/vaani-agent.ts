// Creates (or updates) the Aangan agent in Vaani from prompts/*.md.
//   npx tsx scripts/vaani-agent.ts            create if VAANI_AGENT_ID is empty, else update the prompt
//   npx tsx scripts/vaani-agent.ts --dry-run  print what would be sent
import "./lib";
import fs from "node:fs";

const BASE = "https://api.vaanivoice.ai";
const GREETING = "Hi, this is Aangan Studio's assistant. This call is recorded so our designer has your details. May I know your name?";

export function buildSystemPrompt(): string {
  const agent = fs.readFileSync("prompts/vaani_agent.md", "utf8").trim();
  // Knowledge base without its "paste this" header note. Never includes pricing numbers (see lib/prompts.test.ts).
  const kb = fs.readFileSync("prompts/knowledge_base.md", "utf8").replace(/^#.*\n+(>.*\n)+/m, "").trim();
  return `${agent}\n\n=== STUDIO KNOWLEDGE BASE ===\n${kb}`;
}

/** The customer site sends the same prompt per call (plus the typed CALLER DETAILS), so keep a copy there. */
function syncCustomerSitePrompt(prompt: string) {
  const file = "customer-site/lib/agent-prompt.ts";
  const body = `// GENERATED by scripts/vaani-agent.ts from prompts/vaani_agent.md + prompts/knowledge_base.md. Do not edit by hand.\n// The customer site appends the typed CALLER DETAILS to this for each website call.\nexport const AGENT_PROMPT = ${JSON.stringify(prompt)};\n`;
  fs.writeFileSync(file, body);
  console.log(`Wrote ${file}`);
}

async function main() {
  syncCustomerSitePrompt(buildSystemPrompt());
  if (process.argv.includes("--sync-only")) return;
  const key = process.env.VAANI_API_KEY;
  if (!key) throw new Error("VAANI_API_KEY not set");
  const persona = {
    identity: {
      system_prompt: buildSystemPrompt(),
      personality: { tone: "warm", style: "brief, natural, one question at a time" },
      // The greeting is not interruptible: a stray "okay" or speaker echo must not chop it.
      // user_speech_delay = silence (s) after the caller stops before the agent replies.
      greeting_message: { agent_message: GREETING, agent_speech_delay: 1, user_speech_delay: 2, interruptible: false, let_user_speak_first: false },
    },
    senses_capabilities: {
      language: "en",
      auto_detect: true,
      // Vaani has globally disabled the 'azure' LLM provider (agent saves fail with it), so pin both slots.
      brain: {
        llm: {
          primary: { provider: "google", model: "gemini-3.5-flash", parameters: { temperature: 0.5, top_p: 1, max_tokens: 400 } },
          fallback: { provider: "openai", model: "gpt-4o", parameters: { temperature: 0.5, top_p: 1, max_tokens: 400 } },
          auto_detect: false,
        },
      },
    },
  };
  const agentId = process.env.VAANI_AGENT_ID;
  const [method, url, body] = agentId
    ? ["PATCH", `${BASE}/api/agent/${agentId}/persona`, persona]
    : ["POST", `${BASE}/api/create-agent`, { agent_display_name: "Aangan Studio Assistant", config: { persona } }];
  if (process.argv.includes("--dry-run")) {
    console.log(method, url, JSON.stringify(body).length, "bytes; prompt chars:", persona.identity.system_prompt.length);
    return;
  }
  const res = await fetch(url, { method, headers: { "X-API-Key": key, "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const text = await res.text();
  if (!res.ok) throw new Error(`Vaani ${res.status}: ${text.slice(0, 400)}`);
  const j = JSON.parse(text);
  const id = agentId ?? j.agent_id;
  console.log(agentId ? `Updated persona of agent ${agentId}` : `Created agent ${j.agent_id} (${j.agent_name})`);

  // Turn-taking: Vaani's defaults ("fast" eagerness, 10 s idle hang-up) make the agent talk over
  // callers who pause mid-sentence ("My name is… Anusha") and hang up on thinking callers.
  const experience = {
    conversational_experience: {
      eagerness_to_speak: "slow",
      filler_words: { filler_words_frequency: 0.1 },
    },
    settings: {
      idle_conversation_settings: {
        pulse_check: true,
        end_conversation_on_idle: true,
        idle_call_warning_timeout: 12,
        idle_call_hangup_timeout: 25,
        initial_idle_call_warning_timeout: 8,
        initial_idle_call_hungup_timeout: 30,
        idle_call_warning_message: "Are you still there? Take your time.",
        idle_call_hangup_message: "I'll end the call for now. Feel free to call Aangan Studio back anytime.",
      },
      // Do NOT enable max duration: Vaani treated max_call_duration=12 as seconds and cut every call at ~12 s.
      call_settings: { max_duration_enabled: false, max_call_duration: 30 },
      // Laptop mics in normal rooms trip the noise watcher; be tolerant before hanging up.
      vad_watcher: { empty_transcript_wait: 8, max_consecutive_noise: 6 },
    },
  };
  const ex = await fetch(`${BASE}/api/agent/${id}/experience`, {
    method: "PATCH",
    headers: { "X-API-Key": key, "Content-Type": "application/json" },
    body: JSON.stringify(experience),
  });
  if (!ex.ok) throw new Error(`Vaani experience ${ex.status}: ${(await ex.text()).slice(0, 400)}`);
  console.log("Updated experience (turn-taking, idle, max duration)");
}

main().catch((e) => { console.error(e.message); process.exit(1); });
