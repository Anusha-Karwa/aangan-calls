// Shared helpers for the eval / role-play scripts.
import { config } from "dotenv";
import fs from "node:fs";
import path from "node:path";

config({ path: ".env.local" });

export const TRANSCRIPT_DIR = path.join(process.cwd(), "knowledge", "transcripts");

/** Call time from the transcript header, e.g. "T05 · Phone · 5 September · 10:52am · ..." or "W01 · WhatsApp · 3–4 September". */
export function headerDate(text: string): Date {
  const head = text.split("\n")[0];
  const d = /(\d{1,2})(?:–\d{1,2})?\s+(Sept|September|Oct|October)/.exec(head);
  const t = /(\d{1,2}):(\d{2})\s?(am|pm)/i.exec(head) ?? /(\d{1,2}):(\d{2})\s?(am|pm)/i.exec(text);
  const day = d ? Number(d[1]) : 1;
  const month = d && /^Oct/.test(d[2]) ? 10 : 9;
  let hour = t ? Number(t[1]) % 12 : 11;
  if (t && /pm/i.test(t[3])) hour += 12;
  const iso = `2026-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}T${String(hour).padStart(2, "0")}:${t?.[2] ?? "00"}:00+05:30`;
  return new Date(iso);
}

export function readTranscript(id: string): string {
  return fs.readFileSync(path.join(TRANSCRIPT_DIR, `${id}.txt`), "utf8");
}

/** Replace one marked section of eval-results.md (creating the file/section if needed). */
export function writeResultsSection(key: string, title: string, body: string) {
  const file = path.join(process.cwd(), "eval-results.md");
  let doc = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "# Eval results\n\nGenerated by `npm run eval` and `npm run roleplay`. Re-run after any prompt or rubric change.\n";
  const start = `<!-- ${key}:start -->`;
  const end = `<!-- ${key}:end -->`;
  const section = `${start}\n## ${title}\n\n_Run ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC_\n\n${body.trim()}\n${end}`;
  const re = new RegExp(`${start}[\\s\\S]*?${end}`);
  doc = re.test(doc) ? doc.replace(re, section) : `${doc.trim()}\n\n${section}\n`;
  fs.writeFileSync(file, doc);
}

export function table(headers: string[], rows: (string | number | null | undefined)[][]): string {
  const cell = (v: unknown) => String(v ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
  return [`| ${headers.join(" | ")} |`, `|${headers.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");
}
